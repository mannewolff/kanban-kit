-- ---------------------------------------------------------------------------
-- Gemeldete Messungen der Codeanalyse je Projekt und veroeffentlichtem Stand
-- (Issue #2274, Plan #2272 E2, E3, E8, E12, fachlich #2271)
--
-- Das Workflow-Kit meldet je Veroeffentlichung eine Messung: den veroeffentlichten Stand, seinen
-- Zeitpunkt, ob sie zaehlt (sonst den Grund), die Zahl der Karten und je Zustand — vor der
-- Codeanalyse und Endzustand — die Funde je Art und die geaenderten Zeilen. Gespeichert wird die
-- Meldung roh; die Wochenwerte der Platte „Codeanalyse“ entstehen erst beim Lesen
-- (BefunddichteErmittlung), damit eine nachgemeldete Messung die Woche ihrer Veroeffentlichung
-- aendert (E2). Je Projekt und published_commit gilt die erste Meldung (E3).
--
-- Gespeichert bleibt unbegrenzt, geloescht wird nur mit dem Projekt (E12): Die Menge ist eine
-- Zeile je Veroeffentlichung.
--
-- Rein additiv: Eine aeltere App-Version laeuft gegen dieses Schema unveraendert.
--
-- Rueckweg (Flyway Community kennt kein Undo; von Hand, danach die Zeile von V83 aus
-- flyway_schema_history loeschen):
--   DROP TABLE code_analysis_measurement;
-- ---------------------------------------------------------------------------

-- Je Projekt und veroeffentlichtem Stand eine Zeile. Die Laengen folgen den Grenzen der Meldung
-- (E8). reason ist bei einer zaehlenden Messung leer; die Zustaende duerfen einer nicht zaehlenden
-- fehlen, einer zaehlenden nie. token_name ist bewusst denormalisiert wie in deployment_attempt
-- (V59): Die Meldung bleibt lesbar, auch wenn das Token spaeter widerrufen wird.
CREATE TABLE code_analysis_measurement (
    id                      bigint        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id              bigint        NOT NULL,
    published_commit        varchar(64)   NOT NULL,
    published_at            timestamptz   NOT NULL,
    base_commit             varchar(64)   NOT NULL,
    kit_version             varchar(50)   NOT NULL,
    counts                  boolean       NOT NULL,
    reason                  varchar(100),
    cards                   integer       NOT NULL,
    before_bugs             integer,
    before_vulnerabilities  integer,
    before_code_smells      integer,
    before_changed_lines    integer,
    final_bugs              integer,
    final_vulnerabilities   integer,
    final_code_smells       integer,
    final_changed_lines     integer,
    token_name              varchar(100)  NOT NULL,
    created_at              timestamptz   NOT NULL,
    CONSTRAINT fk_code_analysis_measurement_project FOREIGN KEY (project_id)
        REFERENCES project (id) ON DELETE CASCADE,
    CONSTRAINT uq_code_analysis_measurement_project_commit UNIQUE (project_id, published_commit),
    CONSTRAINT ck_code_analysis_measurement_not_negative CHECK (
        cards >= 0
        AND before_bugs >= 0 AND before_vulnerabilities >= 0
        AND before_code_smells >= 0 AND before_changed_lines >= 0
        AND final_bugs >= 0 AND final_vulnerabilities >= 0
        AND final_code_smells >= 0 AND final_changed_lines >= 0),
    CONSTRAINT ck_code_analysis_measurement_counts_complete CHECK (
        NOT counts
        OR (before_bugs IS NOT NULL AND before_vulnerabilities IS NOT NULL
            AND before_code_smells IS NOT NULL AND before_changed_lines IS NOT NULL
            AND final_bugs IS NOT NULL AND final_vulnerabilities IS NOT NULL
            AND final_code_smells IS NOT NULL AND final_changed_lines IS NOT NULL))
);

CREATE INDEX idx_code_analysis_measurement_project_published
    ON code_analysis_measurement (project_id, published_at);
