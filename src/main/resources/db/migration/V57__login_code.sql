-- ---------------------------------------------------------------------------
-- Anforderungen der Code-Anmeldung (Issue #1803, Plan #1801 A1, A2, A3, A5, fachlich #1781)
--
-- Eine Zeile ist eine Anforderung: der sechsstellige Code und der Link derselben Mail. Beide
-- werden gemeinsam verbraucht (consumed_at), ein neuer Code entwertet den alten samt Link
-- (superseded_at), nach failed_attempts = Maximum gilt keiner von beiden mehr (AK 6).
--
-- email_hash ist der SHA-256 der normalisierten Adresse. Fuer eine unbekannte Adresse entsteht
-- trotzdem eine Zeile, ohne user_id, ohne Code und ohne Link (A5) — damit zaehlt die Grenze je
-- Adresse fuer beide Faelle gleich (AK 7). code_hash ist der HMAC-SHA256 des Codes mit einem
-- Schluessel aus dem Sitzungsgeheimnis (A3), link_hash der SHA-256 des Link-Tokens.
--
-- Der Index auf (email_hash, created_at) traegt Zaehlung, Ersetzen, Code-Einloesung und das
-- Aufraeumen alter Zeilen; der Index auf link_hash die Link-Einloesung.
--
-- Rein additiv: Eine aeltere App-Version laeuft gegen dieses Schema unveraendert.
--
-- Rueckweg (Flyway Community kennt kein Undo; von Hand, danach die Zeile von V57 aus
-- flyway_schema_history loeschen):
--   DROP TABLE login_code;
-- ---------------------------------------------------------------------------

CREATE TABLE login_code (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email_hash      varchar(64)    NOT NULL,
    user_id         bigint         REFERENCES app_user (id) ON DELETE CASCADE,
    code_hash       varchar(64),
    link_hash       varchar(64),
    created_at      timestamptz(6) NOT NULL,
    expires_at      timestamptz(6) NOT NULL,
    failed_attempts integer        NOT NULL DEFAULT 0,
    consumed_at     timestamptz(6),
    superseded_at   timestamptz(6),
    CONSTRAINT chk_login_code_failed_attempts CHECK (failed_attempts >= 0),
    CONSTRAINT chk_login_code_expiry CHECK (expires_at > created_at),
    CONSTRAINT chk_login_code_secrets
        CHECK ((code_hash IS NULL) = (link_hash IS NULL) AND (code_hash IS NULL) = (user_id IS NULL))
);
CREATE INDEX idx_login_code_email_created ON login_code (email_hash, created_at);
CREATE INDEX idx_login_code_link ON login_code (link_hash);
