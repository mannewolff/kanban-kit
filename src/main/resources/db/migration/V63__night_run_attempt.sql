-- Vorgaenge je Arbeitspaket eines Nachtlaufs (Issue #1944, Plan #1905 E1, E4, E5)
--
-- Eine Zeile ist ein einzelner Versuch an einer Karte in einer Stufe der Kette, je Pruefer einer
-- Pruefung eine eigene. Anders als night_run_item_stage (V37) traegt eine Stufe hier beliebig
-- viele Zeilen je Paket; position haelt die Reihenfolge der Ausfuehrung, wie gemeldet.
--
-- model und effort duerfen fehlen (E6): NULL heisst "nicht gemeldet". Die Verbrauchsspalten
-- tragen dieselben Namen wie an night_run_item_stage, damit VerbrauchEmbeddable sie liest.
--
-- written_card_numbers ist die erste Array-Spalte im Schema (E4): die Karten der Dokumente, die
-- der Vorgang geschrieben hat, in gemeldeter Reihenfolge. Eine leere Liste ist ein leeres Array,
-- nie NULL.
--
-- run_complete ist der Wert complete des Laufs aus der Meldung, die die Vorgaenge schrieb. Eine
-- Meldung des Kits ersetzt den Stand des Laufs samt Vorgaengen (E5); der Wert ist darum der der
-- letzten Meldung.
--
-- Lebenslauf: Mit dem Arbeitspaket entfallen seine Vorgaenge (ON DELETE CASCADE).
--
-- Rein additiv: Eine aeltere App-Version laeuft gegen dieses Schema unveraendert.
--
-- Rueckweg (Flyway Community kennt kein Undo; von Hand, danach die Zeile von V63 aus
-- flyway_schema_history loeschen):
--   DROP TABLE night_run_attempt;
-- ---------------------------------------------------------------------------

CREATE TABLE night_run_attempt (
    id                   bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    night_run_item_id    bigint        NOT NULL,
    position             integer       NOT NULL,
    stage                varchar(16)   NOT NULL,
    card_number          integer       NOT NULL,
    model                varchar(100),
    effort               varchar(20),
    succeeded            boolean       NOT NULL,
    cost_usd             numeric(12,6),
    input_tokens         bigint,
    output_tokens        bigint,
    cached_input_tokens  bigint,
    model_duration_ms    bigint,
    turns                integer,
    written_card_numbers integer[]     NOT NULL DEFAULT '{}',
    run_complete         boolean       NOT NULL,
    CONSTRAINT fk_night_run_attempt_item FOREIGN KEY (night_run_item_id)
        REFERENCES night_run_item (id) ON DELETE CASCADE,
    CONSTRAINT ck_night_run_attempt_stage
        CHECK (stage IN ('PLAN', 'REVIEW', 'PAKETE', 'ABDECKUNG', 'UMSETZUNG')),
    CONSTRAINT ck_night_run_attempt_model_length CHECK (char_length(model) <= 100),
    CONSTRAINT ck_night_run_attempt_effort_length CHECK (char_length(effort) <= 20),
    CONSTRAINT ck_night_run_attempt_written_cards_length
        CHECK (cardinality(written_card_numbers) <= 50)
);
CREATE INDEX idx_night_run_attempt_item ON night_run_attempt (night_run_item_id);
