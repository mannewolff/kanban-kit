-- ---------------------------------------------------------------------------
-- Label-Ereignisse mit Herkunft (Issue #1754, Plan #1752 E2, E7, E11, fachlich #1750)
--
-- Die Zuordnung card_label (V12) traegt weder Zeitpunkt noch Herkunft. Die Platte
-- „Nacharbeit“ muss aber wissen, ob ein Nachtlauf ein Halt-Label gesetzt hat. Darum haelt
-- card_label_event jedes tatsaechliche Hinzufuegen eines Labels fest, mit dem Stempel aus
-- ActorContext — dieselbe Quelle wie card_activity (V23, V47). Abnehmen wird nicht erfasst.
--
-- label_name ist ein Schnappschuss (Laenge wie label.name, V12): Ein spaeter umbenanntes oder
-- geloeschtes Label aendert nicht, was damals gesetzt wurde. Darum kein Fremdschluessel auf
-- label. token_name folgt seiner Quelle kanban_access_token.display_name varchar(120) wie
-- V32 und V52; agent bleibt bei varchar(100), der Header wird auf 100 Zeichen gekappt.
-- origin ist nullable: Ein Aufruf ohne authentifizierten Kontext (interne Aufrufe) traegt
-- keine Herkunft, wie ein Alt-Eintrag in card_activity.
--
-- card_label_event_capture haelt in genau einer Zeile fest, seit wann erfasst wird (E7): Vor
-- dieser Migration ist die Herkunft eines Labels nicht bestimmbar, eine 0 behauptete dort
-- „kein Halt“. Kein Backfill.
--
-- Rein additiv: Eine aeltere App-Version laeuft gegen dieses Schema unveraendert.
--
-- Rueckweg (Flyway Community kennt kein Undo; von Hand, danach die Zeile von V55 aus
-- flyway_schema_history loeschen):
--   DROP TABLE card_label_event_capture;
--   DROP TABLE card_label_event;
-- ---------------------------------------------------------------------------

CREATE TABLE card_label_event (
    id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    card_id        bigint          NOT NULL REFERENCES card (id) ON DELETE CASCADE,
    label_name     varchar(60)     NOT NULL,
    created_at     timestamptz(6)  NOT NULL,
    origin         varchar(10),
    token_name     varchar(120),
    agent          varchar(100),
    run_started_at timestamptz,
    CONSTRAINT chk_card_label_event_origin
        CHECK (origin IS NULL OR origin IN ('SESSION', 'TOKEN'))
);
CREATE INDEX idx_card_label_event_card ON card_label_event (card_id, created_at);

CREATE TABLE card_label_event_capture (
    since timestamptz NOT NULL
);
INSERT INTO card_label_event_capture (since) VALUES (now());
