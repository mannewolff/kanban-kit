-- Ansicht als XY: Zustand und Protokoll der Vorschau (Issue #1917, Plan #1914 E2, E3, E9, E12)
--
-- Eine Zeile ist eine Vorschau: ein Plattform-Admin (admin_id) sieht die App nur lesend als ein
-- anderes Konto (ziel_id). Die Tabelle ist zugleich Zustand und Protokoll (E12): Start und Ende
-- stehen in derselben Zeile.
--
-- kennung ist die oeffentliche Kennung aus dem Cookie, geheimnis_hash der SHA-256 des Geheimnisses
-- daneben — der Klartext steht nirgends in der Datenbank (E2). sitzungs_generation haelt die
-- Generation der Anmeldung beim Start fest; eine hoehere beendet die Vorschau (E3).
--
-- Lebenslauf (E12): Mit dem Zielkonto entfallen seine Eintraege (ON DELETE CASCADE). Wird das
-- Konto des Admins geloescht, bleibt der Eintrag stehen, admin_id wird leer, und admin_name nennt
-- ihn weiter (Schnappschuss beim Start).
--
-- beendet_am und endgrund gibt es nur gemeinsam. Bei Ablauf ist beendet_am der Ablaufzeitpunkt.
--
-- Die Eindeutigkeit der Kennung bringt ihren Index mit (Pruefung je Anfrage); der Index auf
-- ziel_id traegt das Protokoll je Zielkonto.
--
-- Rein additiv: Eine aeltere App-Version laeuft gegen dieses Schema unveraendert.
--
-- Rueckweg (Flyway Community kennt kein Undo; von Hand, danach die Zeile von V62 aus
-- flyway_schema_history loeschen):
--   DROP TABLE admin_vorschau;
-- ---------------------------------------------------------------------------

CREATE TABLE admin_vorschau (
    id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kennung             varchar(64)    NOT NULL,
    geheimnis_hash      varchar(64)    NOT NULL,
    admin_id            bigint         REFERENCES app_user (id) ON DELETE SET NULL,
    admin_name          varchar(120)   NOT NULL,
    ziel_id             bigint         NOT NULL REFERENCES app_user (id) ON DELETE CASCADE,
    sitzungs_generation bigint         NOT NULL,
    gestartet_am        timestamptz(6) NOT NULL,
    laeuft_ab_am        timestamptz(6) NOT NULL,
    beendet_am          timestamptz(6),
    endgrund            varchar(32),
    CONSTRAINT uq_admin_vorschau_kennung UNIQUE (kennung),
    CONSTRAINT chk_admin_vorschau_ablauf CHECK (laeuft_ab_am > gestartet_am),
    CONSTRAINT chk_admin_vorschau_ende CHECK ((beendet_am IS NULL) = (endgrund IS NULL)),
    CONSTRAINT chk_admin_vorschau_endgrund CHECK (endgrund IN (
        'BEENDET', 'ABLAUF', 'ABMELDUNG', 'ROLLE_ENTZOGEN', 'ADMIN_GESPERRT',
        'SITZUNG_UNGUELTIG', 'ZIEL_IST_ADMIN', 'ZIEL_FEHLT'))
);
CREATE INDEX idx_admin_vorschau_ziel ON admin_vorschau (ziel_id);
