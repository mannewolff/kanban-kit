-- ---------------------------------------------------------------------------
-- Zustandsaufenthalte der Arbeitspakete (Issue #1767, Plan #1765 E1, E3, E8, E20, fachlich #1751)
--
-- Die Platten „Fluss“ und „Alter in Arbeit“ zählen ein Arbeitspaket nach seinem Zustand
-- (card.status, V46), nicht nach der Spalte. card_column_transition (V9) kennt den Zustand
-- nicht, card_activity haelt weder Board noch Papierkorb fest. Darum haelt card_flow_stay je
-- Zeile einen Aufenthalt in einem Zustand auf einem Board fest. status NULL heisst „Zustand
-- unbekannt“ und kommt nur aus dem einmaligen Nachtrag. entered_known sagt, ob entered_at der
-- wirkliche Eintritt ist. ended_by haelt fest, warum ein Aufenthalt endete: Zustandswechsel,
-- Boardwechsel oder Verlassen des Flusses (Papierkorb, Archiv, Artwechsel).
--
-- Eine endgueltig geloeschte Karte faellt rueckwirkend heraus (ON DELETE CASCADE, AK 16).
--
-- card_flow_capture haelt in genau einer Zeile fest, seit wann erfasst wird (since), und ob
-- der einmalige Nachtrag aus dem Spaltenverlauf gelaufen ist (reconstructed_at, E20).
--
-- Saat: Jede Karte im Fluss (E3 — mit Zustand, nicht im Papierkorb, nicht archiviert oder
-- fertig) bekommt einen offenen Aufenthalt ab since mit unbekanntem Eintritt; der Nachtrag
-- korrigiert ihn. Ausgenommen sind fertige Karten mit moved_to_done_at: Der Wert ist ihr
-- letzter Done-Eintritt, sie beginnen dort mit bekanntem Eintritt — sonst zaehlte das
-- Done-Band vor oder ohne Nachtrag jede je fertige Karte als heute fertig.
--
-- Rein additiv: Eine aeltere App-Version laeuft gegen dieses Schema unveraendert.
--
-- Rueckweg (Flyway Community kennt kein Undo; von Hand, danach die Zeile von V56 aus
-- flyway_schema_history loeschen):
--   DROP TABLE card_flow_capture;
--   DROP TABLE card_flow_stay;
-- ---------------------------------------------------------------------------

CREATE TABLE card_flow_stay (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    card_id       bigint       NOT NULL REFERENCES card (id) ON DELETE CASCADE,
    board_id      bigint       NOT NULL REFERENCES board (id) ON DELETE CASCADE,
    status        varchar(20),
    entered_at    timestamptz  NOT NULL,
    left_at       timestamptz,
    entered_known boolean      NOT NULL,
    ended_by      varchar(10),
    CONSTRAINT chk_card_flow_stay_status
        CHECK (status IS NULL OR status IN ('BACKLOG', 'READY', 'IN_PROGRESS', 'IN_REVIEW', 'DONE')),
    CONSTRAINT chk_card_flow_stay_ended_by
        CHECK (ended_by IS NULL OR ended_by IN ('STATUS', 'BOARD', 'EXIT'))
);
CREATE INDEX idx_card_flow_stay_board ON card_flow_stay (board_id, entered_at);
CREATE INDEX idx_card_flow_stay_card ON card_flow_stay (card_id, left_at);

CREATE TABLE card_flow_capture (
    since            timestamptz NOT NULL,
    reconstructed_at timestamptz
);
INSERT INTO card_flow_capture (since) VALUES (now());

INSERT INTO card_flow_stay (card_id, board_id, status, entered_at, entered_known)
SELECT c.id,
       c.board_id,
       c.status,
       CASE WHEN c.status = 'DONE' AND c.moved_to_done_at IS NOT NULL
            THEN c.moved_to_done_at
            ELSE f.since
       END,
       c.status = 'DONE' AND c.moved_to_done_at IS NOT NULL
FROM card c
CROSS JOIN card_flow_capture f
WHERE c.status IS NOT NULL
  AND c.deleted_at IS NULL
  AND (NOT c.archived OR c.status = 'DONE');
