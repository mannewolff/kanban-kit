-- ---------------------------------------------------------------------------
-- Gemeldete Auslieferungsversuche je Projekt: POST /api/kanban/deployments
-- (Issue #1833, Plan #1831 A2, E3, E6, E12, fachlich #1784)
--
-- Ein Auslieferungslauf meldet je Versuch einmal: Kennung, Ausgang, Zeitpunkt des Ausgangs, den
-- ausgelieferten Stand und die Commits seit dem vorigen gemeldeten Stand. Gespeichert wird jede
-- Meldung vollstaendig; die Kennzahlen der Platte „Auslieferung“ entstehen erst beim Lesen
-- (AuslieferungsErmittlung), damit die Reihenfolge des Eingangs nichts entscheidet (E6).
--
-- Gespeichert bleibt unbegrenzt, geloescht wird nur mit dem Projekt (E12): Ein Ausfall kann vor
-- dem Fenster beginnen, und die Menge (einige Versuche je Tag) ist klein.
--
-- Rein additiv: Eine aeltere App-Version laeuft gegen dieses Schema unveraendert.
--
-- Rueckweg (Flyway Community kennt kein Undo; von Hand, in dieser Reihenfolge, danach die
-- Zeile von V59 aus flyway_schema_history loeschen):
--   DROP TABLE deployment_commit;
--   DROP TABLE deployment_attempt;
-- ---------------------------------------------------------------------------

-- Je Versuch eine Zeile. Dieselbe Kennung zaehlt je Projekt nur einmal (E3); id steigt mit dem
-- Eingang und entscheidet den Gleichstand zweier Versuche mit demselben finished_at. token_name
-- ist bewusst denormalisiert wie in card_activity (V23): Die Meldung bleibt lesbar, auch wenn
-- das Token spaeter widerrufen wird.
CREATE TABLE deployment_attempt (
    id          bigint        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id  bigint        NOT NULL,
    attempt_id  varchar(200)  NOT NULL,
    outcome     varchar(10)   NOT NULL,
    finished_at timestamptz   NOT NULL,
    revision    varchar(64)   NOT NULL,
    token_name  varchar(100)  NOT NULL,
    created_at  timestamptz   NOT NULL,
    CONSTRAINT fk_deployment_attempt_project FOREIGN KEY (project_id)
        REFERENCES project (id) ON DELETE CASCADE,
    CONSTRAINT uq_deployment_attempt_project_attempt UNIQUE (project_id, attempt_id),
    CONSTRAINT ck_deployment_attempt_outcome CHECK (outcome IN ('SUCCESS', 'FAILURE'))
);

CREATE INDEX idx_deployment_attempt_project_finished
    ON deployment_attempt (project_id, finished_at);

-- Je gemeldetem Commit eines Versuchs eine Zeile. Derselbe sha darf in mehreren Versuchen stehen
-- (E6): Welcher Versuch ihn zuerst meldete und welcher ihn auslieferte, rechnet erst das Lesen.
-- project_id steht doppelt, damit das Laden je Projekt ohne Umweg ueber den Versuch auskommt.
CREATE TABLE deployment_commit (
    attempt_ref  bigint        NOT NULL,
    project_id   bigint        NOT NULL,
    sha          varchar(64)   NOT NULL,
    committed_at timestamptz   NOT NULL,
    CONSTRAINT pk_deployment_commit PRIMARY KEY (attempt_ref, sha),
    CONSTRAINT fk_deployment_commit_attempt FOREIGN KEY (attempt_ref)
        REFERENCES deployment_attempt (id) ON DELETE CASCADE,
    CONSTRAINT fk_deployment_commit_project FOREIGN KEY (project_id)
        REFERENCES project (id) ON DELETE CASCADE
);

CREATE INDEX idx_deployment_commit_project_sha
    ON deployment_commit (project_id, sha);
