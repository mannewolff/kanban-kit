-- ---------------------------------------------------------------------------
-- Push-Abos je Geraet (Issue #1997, Plan #1989 E12, E13, E14; Fachliche Quelle #1961 AK 11, 12, 14)
--
-- push_abo steht fuer ein Geraet: der Endpunkt des Push-Dienstes mit den Schluesseln des Browsers
-- (base64url). gilt_bis ist das Ende der Sitzung, mit der das Abo zuletzt angelegt oder
-- aufgefrischt wurde; danach meldet der Meldejob nichts mehr. angelegt_at trennt, was schon vor dem
-- Einschalten bestand und nicht nachgemeldet wird (E12).
--
-- push_abo_board_aus haelt die abgeschalteten Boards eines Abos: Eingeschaltet heisst fuer alle
-- Boards an, bis man eines abschaltet (E13).
--
-- push_lauf_gemeldet haelt je Lauf fest, dass er gemeldet wurde, und macht "hoechstens eine
-- Nachricht je Lauf" unabhaengig von der Aufbewahrung der Outbox (E12).
--
-- Loeschketten: Konto -> Abo -> Board-Schalter, Board -> Board-Schalter, Lauf -> Meldung.
-- ---------------------------------------------------------------------------
CREATE TABLE push_abo (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     BIGINT         NOT NULL REFERENCES app_user (id) ON DELETE CASCADE,
    endpoint    VARCHAR(2048)  NOT NULL,
    p256dh      VARCHAR(128)   NOT NULL,
    auth        VARCHAR(64)    NOT NULL,
    angelegt_at timestamptz(6) NOT NULL,
    gilt_bis    timestamptz(6) NOT NULL,
    CONSTRAINT uq_push_abo_endpoint UNIQUE (endpoint)
);

CREATE INDEX idx_push_abo_user ON push_abo (user_id);

CREATE TABLE push_abo_board_aus (
    abo_id   BIGINT NOT NULL REFERENCES push_abo (id) ON DELETE CASCADE,
    board_id BIGINT NOT NULL REFERENCES board (id) ON DELETE CASCADE,
    PRIMARY KEY (abo_id, board_id)
);

CREATE INDEX idx_push_abo_board_aus_board ON push_abo_board_aus (board_id);

CREATE TABLE push_lauf_gemeldet (
    night_run_id BIGINT         PRIMARY KEY REFERENCES night_run (id) ON DELETE CASCADE,
    gemeldet_at  timestamptz(6) NOT NULL,
    grund        VARCHAR(32)    NOT NULL
);
