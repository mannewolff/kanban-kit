-- ---------------------------------------------------------------------------
-- Benachrichtigung per Mail (Issue #2073, Plan #2070 E1, E4, E7, E14; Fachliche Quelle #2060)
--
-- benachrichtigung_projekt und benachrichtigung_person sind die Schalter: Je eingeschaltetem
-- Schalter eine Zeile mit dem Einschaltzeitpunkt, keine Zeile heisst ausgeschaltet. Was vor dem
-- Einschalten eintrat, wird daran erkannt und nicht nachgemeldet.
--
-- benachrichtigung_ruhezeit haelt je Person Beginn, Ende und IANA-Zone; sie gilt ueber alle
-- Projekte.
--
-- benachrichtigung_anlass macht "hoechstens eine Mail" zur Regel der Datenbank (E4): eindeutig je
-- (lauf_id, art) und je label_event_id. Ein Anlass haengt an einem Lauf oder einem Label-Ereignis,
-- darum sind beide Spalten NULL-faehig; card_id ist NULL, wenn keine Karte zugeordnet ist.
--
-- benachrichtigung_zustellung ist je Anlass und Person eine Zeile. verschoben wird beim Anlegen
-- gesetzt, wenn die Ruhezeit greift, und sagt dem Versand, was in die Sammelmail gehoert.
--
-- Loeschketten (E14): Karte, Projekt, Person, Lauf und Label-Ereignis nehmen ihre abhaengigen
-- Zeilen mit, der Anlass seine Zustellungen. Die Aufbewahrung von 90 Tagen uebernimmt ein Job.
--
-- Rein additiv: Eine aeltere App-Version laeuft gegen dieses Schema unveraendert.
--
-- Rueckweg (Flyway Community kennt kein Undo; von Hand, danach die Zeile von V69 aus
-- flyway_schema_history loeschen):
--   DROP TABLE benachrichtigung_zustellung;
--   DROP TABLE benachrichtigung_anlass;
--   DROP TABLE benachrichtigung_ruhezeit;
--   DROP TABLE benachrichtigung_person;
--   DROP TABLE benachrichtigung_projekt;
-- ---------------------------------------------------------------------------
CREATE TABLE benachrichtigung_projekt (
    project_id         BIGINT         PRIMARY KEY REFERENCES project (id) ON DELETE CASCADE,
    eingeschaltet_seit timestamptz(6) NOT NULL
);

CREATE TABLE benachrichtigung_person (
    user_id            BIGINT         NOT NULL REFERENCES app_user (id) ON DELETE CASCADE,
    project_id         BIGINT         NOT NULL REFERENCES project (id) ON DELETE CASCADE,
    eingeschaltet_seit timestamptz(6) NOT NULL,
    PRIMARY KEY (user_id, project_id)
);

CREATE INDEX idx_benachrichtigung_person_project ON benachrichtigung_person (project_id);

CREATE TABLE benachrichtigung_ruhezeit (
    user_id  BIGINT      PRIMARY KEY REFERENCES app_user (id) ON DELETE CASCADE,
    beginn   TIME        NOT NULL,
    ende     TIME        NOT NULL,
    zeitzone VARCHAR(64) NOT NULL
);

CREATE TABLE benachrichtigung_anlass (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    art            VARCHAR(20)    NOT NULL,
    project_id     BIGINT         NOT NULL REFERENCES project (id) ON DELETE CASCADE,
    lauf_id        BIGINT         REFERENCES night_run (id) ON DELETE CASCADE,
    label_event_id BIGINT         REFERENCES card_label_event (id) ON DELETE CASCADE,
    card_id        BIGINT         REFERENCES card (id) ON DELETE CASCADE,
    eingetreten_at timestamptz(6) NOT NULL,
    angelegt_at    timestamptz(6) NOT NULL,
    CONSTRAINT ck_benachrichtigung_anlass_art CHECK (art IN
        ('LAUF_WARTET', 'STOERUNG', 'UEBERSICHT', 'KARTE_FRAGE', 'KARTE_GESCHUETZT')),
    CONSTRAINT uq_benachrichtigung_anlass_lauf_art UNIQUE (lauf_id, art),
    CONSTRAINT uq_benachrichtigung_anlass_label_event UNIQUE (label_event_id)
);

CREATE INDEX idx_benachrichtigung_anlass_project ON benachrichtigung_anlass (project_id);
CREATE INDEX idx_benachrichtigung_anlass_card ON benachrichtigung_anlass (card_id);

CREATE TABLE benachrichtigung_zustellung (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    anlass_id  BIGINT         NOT NULL REFERENCES benachrichtigung_anlass (id) ON DELETE CASCADE,
    user_id    BIGINT         NOT NULL REFERENCES app_user (id) ON DELETE CASCADE,
    faellig_ab timestamptz(6) NOT NULL,
    verschoben BOOLEAN        NOT NULL,
    zustand    VARCHAR(12)    NOT NULL,
    CONSTRAINT ck_benachrichtigung_zustellung_zustand CHECK (zustand IN
        ('OFFEN', 'EINGEPLANT', 'ENTFALLEN', 'ZUGESTELLT')),
    CONSTRAINT uq_benachrichtigung_zustellung_anlass_user UNIQUE (anlass_id, user_id)
);

CREATE INDEX idx_benachrichtigung_zustellung_user ON benachrichtigung_zustellung (user_id);
